// Regenerates js/data.js from data/participants.csv
// Usage: node scripts/build-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const csv = readFileSync(join(root, 'data/participants.csv'), 'utf8').trim();

function parseLine(line) {
  const out = []; let cur = ''; let q = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) { if (c === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (c === '"') q = false; else cur += c; }
    else if (c === '"') q = true; else if (c === ',') { out.push(cur); cur = ''; } else cur += c;
  }
  out.push(cur); return out;
}

const [head, ...lines] = csv.split(/\r?\n/);
const keys = parseLine(head);
const rows = lines.filter(Boolean).map(l => {
  const v = parseLine(l); const o = {};
  keys.forEach((k, i) => (o[k] = (v[i] || '').trim()));
  return { n: o.name, r: o.roll.toUpperCase(), d: o.dept, y: Number(o.year), e: o.email.toLowerCase() };
});

const rolls = new Set();
for (const p of rows) { if (rolls.has(p.r)) console.warn('Duplicate roll:', p.r); rolls.add(p.r); }

writeFileSync(join(root, 'js/data.js'),
  `// AUTO-GENERATED by scripts/build-data.mjs from data/participants.csv — do not edit by hand.\n` +
  `window.AF_PARTICIPANTS = ${JSON.stringify(rows)};\n`);
console.log(`js/data.js written: ${rows.length} participants`);
